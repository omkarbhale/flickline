import { countRows, type Row, type Status } from './conformance';
import type { SpecSnapshot } from './specParse';

/**
 * Renders `docs/conformance.md` from evaluated rows. Pure text: the same rows always give the same
 * bytes (no dates, no commit ids), so a stale table is detectable by comparing strings.
 */

const STATUS_TEXT: Record<Status, string> = {
  match: 'match',
  'match-estimate': 'match (estimate)',
  'match-placeholder': 'match (placeholder)',
  deviation: '**deviation**',
  'not-implemented': 'not implemented',
};

/** Escape a value for a markdown table cell. */
function cell(s: string): string {
  return s.replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');
}

export function renderTable(rows: readonly Row[], snap: SpecSnapshot): string {
  const c = countRows(rows);
  const out: string[] = [];
  out.push('# Conformance table');
  out.push('');
  out.push(
    '<!-- Generated by `npm run conformance` from docs/mechanics-spec.md, src/config and the real simulation. Do not edit by hand. -->',
  );
  out.push('');
  out.push(
    `Does every implemented value and measurable behaviour equal \`docs/mechanics-spec.md\` (research date ${snap.spec.researchDate}, reference build ${snap.spec.build})? One row per spec value or behaviour. This is the numbers track of design §14.7 (issue #61); the suite is issue #64.`,
  );
  out.push('');
  out.push('## Summary');
  out.push('');
  out.push('| Status | Rows |');
  out.push('|---|---|');
  out.push(`| match (value taken from a source) | ${c.match} |`);
  out.push(`| match (estimate) | ${c.matchEstimate} |`);
  out.push(`| match (placeholder) | ${c.matchPlaceholder} |`);
  out.push(`| deviation (reason written) | ${c.deviation} |`);
  out.push(`| not implemented | ${c.notImplemented} |`);
  out.push(`| **total** | **${c.total}** |`);
  out.push('');
  out.push('## How to read it');
  out.push('');
  out.push('- **match**: the implemented value equals the spec value, and the spec itself sources it (OFFICIAL, DATA, COMMUNITY, DERIVED, or confidence H or M in §7.1).');
  out.push('- **match (estimate)** and **match (placeholder)**: equal to the spec, but the spec marks the number as an estimate (confidence L, ESTIMATE) or a design placeholder (P, PLACEHOLDER). It matches a guess, not a measurement. Tune these by feel and by measuring the reference game, then update the spec.');
  out.push('- **deviation**: the implementation differs. The Note column holds the written reason and where it is being fixed. A differing row without a reason fails the suite.');
  out.push('- **not implemented**: nothing to compare yet. This is not a failure; the row flips to match or deviation when the mechanic lands (the Note column says what is missing).');
  out.push('- **Spec** is the value in `docs/mechanics-spec.md`; **Tag** is the spec\'s own confidence tag; **Implemented** is the value read from the live `config/` key or measured on the real simulation; **Checked by** says which; the row id is the name of the test in `src/conformance/conformance.test.ts` (`npm test`).');
  out.push('');
  out.push('Regenerate with `npm run conformance` after changing `docs/mechanics-spec.md`, `src/config/` or the simulation. `npm test` fails when this file is out of date.');
  out.push('');

  const areas: string[] = [];
  for (const r of rows) if (!areas.includes(r.area)) areas.push(r.area);
  for (const area of areas) {
    out.push(`## ${area}`);
    out.push('');
    out.push('| Row | § | Spec | Tag | Implemented | Checked by | Status | Note |');
    out.push('|---|---|---|---|---|---|---|---|');
    for (const r of rows.filter((x) => x.area === area)) {
      out.push(
        `| \`${cell(r.id)}\` | ${cell(r.section)} | ${cell(r.spec)} | ${cell(r.tag.text)} | ${cell(r.implemented)} | ${cell(r.via)} | ${STATUS_TEXT[r.status]} | ${cell(r.note)} |`,
      );
    }
    out.push('');
  }
  return out.join('\n') + '\n';
}
